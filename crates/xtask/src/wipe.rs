const CHECK: &str = "check-wipe";

/// The harness crate's name, as its symbols carry it.
const HARNESS: &str = "ironafs_wipe_gate";

/// The buffer's length in every case.
const LENGTH: usize = 64;

/// The harness's source: each case a function of its own, never inlined
/// into another, so its body is found by name.
pub(crate) const HARNESS_SOURCE: &str = "//! Generated by `cargo xtask check-wipe`; never shipped.\n\
\n\
/// A buffer read after the wipe.\n\
#[inline(never)]\n\
pub fn wiped_live(fill: u8) -> u8 {\n\
    let mut buffer = [fill; 64];\n\
    core::hint::black_box(&mut buffer);\n\
    ironafs_os::wipe(&mut buffer);\n\
    buffer.iter().fold(0, |all, byte| all | byte)\n\
}\n\
\n\
/// A buffer on the stack, wiped just before it goes out of scope.\n\
#[inline(never)]\n\
pub fn wiped_dead(fill: u8) {\n\
    let mut buffer = [fill; 64];\n\
    ironafs_os::wipe(&mut buffer);\n\
}\n\
\n\
/// The control: `wipe`'s body with a plain write in place of the\n\
/// volatile one, the fence kept.\n\
#[inline(never)]\n\
pub fn plain_dead(fill: u8) {\n\
    let mut buffer = [fill; 64];\n\
    for byte in buffer.iter_mut() {\n\
        *byte = 0;\n\
    }\n\
    core::sync::atomic::compiler_fence(core::sync::atomic::Ordering::SeqCst);\n\
}\n\
\n\
/// The same buffer with no overwrite at all.\n\
#[inline(never)]\n\
pub fn untouched_dead(fill: u8) {\n\
    let buffer = [fill; 64];\n\
    core::mem::drop(buffer);\n\
}\n";

/// The architectures of the Linux targets, by their zero byte store.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Arch {
    /// `movb $0, <memory>`.
    X86_64,
    /// `strb wzr, <memory>`.
    Aarch64,
}

impl Arch {
    fn of(target: &str) -> Option<Self> {
        if target.starts_with("x86_64-") {
            Some(Self::X86_64)
        } else if target.starts_with("aarch64-") {
            Some(Self::Aarch64)
        } else {
            None
        }
    }
}

/// The `[profile.release]` table of a manifest, up to the next table.
/// What it misses is caught by comparing the compiled options
/// in `release_assembly`.
pub(crate) fn profile_table(manifest: &str) -> Option<String> {
    let mut lines = manifest.lines();
    lines
        .by_ref()
        .find(|line| line.trim() == "[profile.release]")?;
    let mut table: Vec<&str> = lines
        .take_while(|line| !line.trim_start().starts_with('['))
        .collect();
    while table.last().is_some_and(|line| line.trim().is_empty()) {
        table.pop();
    }
    let mut text = "[profile.release]\n".to_owned();
    for line in table {
        text.push_str(line);
        text.push('\n');
    }
    Some(text)
}

/// The symbol a label line defines.
fn label(line: &str) -> Option<&str> {
    if line.starts_with(char::is_whitespace) {
        return None;
    }
    line.strip_suffix(':')
}

/// Whether `symbol` names the function `name`: a symbol of the harness
/// crate holding `name` with its length before it, as both Rust manglings
/// write it, and no further name character after it.
fn names(symbol: &str, name: &str) -> bool {
    let prefix = format!("{}{HARNESS}{}{name}", HARNESS.len(), name.len());
    if let Some(path) = symbol.strip_prefix("_RNvC") {
        let path = if let Some(disambiguator) = path.strip_prefix('s') {
            let Some((_, path)) = disambiguator.split_once('_') else {
                return false;
            };
            path
        } else {
            path
        };
        return path
            .strip_prefix(&prefix)
            .is_some_and(|suffix| suffix.is_empty() || suffix.starts_with('.'));
    }
    symbol
        .strip_prefix("_ZN")
        .and_then(|path| path.strip_prefix(&prefix))
        .and_then(|suffix| suffix.strip_prefix("17h"))
        .and_then(|suffix| suffix.split_once('E'))
        .is_some_and(|(hash, suffix)| {
            hash.len() == 16
                && hash.bytes().all(|byte| byte.is_ascii_hexdigit())
                && (suffix.is_empty() || suffix.starts_with('.'))
        })
}

/// How many lines of `lines` store a zero byte to memory.
pub(crate) fn zero_byte_stores(lines: &[&str], arch: Arch) -> usize {
    let (mnemonic, source) = match arch {
        Arch::X86_64 => ("movb", "$0,"),
        Arch::Aarch64 => ("strb", "wzr,"),
    };
    lines
        .iter()
        .filter(|line| {
            let mut words = line.split_whitespace();
            words.next() == Some(mnemonic) && words.next() == Some(source)
        })
        .count()
}

/// `text` with the numbers after each local label prefix (`.LBB`,
/// `.Ltmp`) dropped, so two functions' labels compare equal.
fn without_label_numbers(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some((head, tail)) = [".LBB", ".Ltmp"]
        .iter()
        .filter_map(|prefix| rest.find(prefix).map(|at| at + prefix.len()))
        .min()
        .and_then(|end| rest.split_at_checked(end))
    {
        out.push_str(head);
        rest = tail.trim_start_matches(|c: char| c.is_ascii_digit() || c == '_');
    }
    out.push_str(rest);
    out
}

/// The instructions of `lines`, without directives, labels or comments,
/// with whitespace collapsed and local label numbers dropped.
pub(crate) fn normalized(lines: &[&str]) -> Vec<String> {
    lines
        .iter()
        .map(|line| line.trim())
        .filter(|line| {
            !line.is_empty()
                && !line.starts_with('.')
                && !line.starts_with('#')
                && !line.starts_with("//")
                && !line.ends_with(':')
        })
        .map(|line| without_label_numbers(&line.split_whitespace().collect::<Vec<_>>().join(" ")))
        .collect()
}

/// Judges one target's assembly; returns every problem found.
fn judge<'a>(shards: impl IntoIterator<Item = &'a str>, arch: Arch) -> Result<(), Vec<String>> {
    let symbols = Symbols::index(shards).map_err(|problem| vec![problem.to_owned()])?;
    let mut problems = Vec::new();
    for case in ["wiped_live", "wiped_dead"] {
        let lines = match symbols.body(case) {
            Ok(lines) => lines,
            Err(problem) => {
                problems.push(format!("`{case}`: {problem}"));
                continue;
            }
        };
        // `10ironafs_os` is the crate's name as both manglings write it.
        if lines.iter().any(|line| line.contains("10ironafs_os")) {
            problems.push(format!(
                "`{case}` refers to ironafs-os, so `wipe` is not inlined there and the case \
                 shows nothing"
            ));
        }
        let stores = zero_byte_stores(&lines, arch);
        if stores < LENGTH {
            problems.push(format!(
                "`{case}` has {stores} zero byte stores for a buffer of {LENGTH} bytes"
            ));
        }
    }
    match (symbols.body("plain_dead"), symbols.body("untouched_dead")) {
        (Ok(plain), Ok(untouched)) => {
            let plain = normalized(&plain);
            let untouched = normalized(&untouched);
            if plain.is_empty() || untouched.is_empty() {
                problems.push("assembly control has no instructions".to_owned());
            } else if plain != untouched {
                problems.push(
                    "the control `plain_dead` (a plain overwrite, the fence kept) compiles to \
                     more than `untouched_dead`: its stores survive, so the dead-buffer case \
                     shows nothing on this target"
                        .to_owned(),
                );
            }
        }
        (Err(problem), _) | (_, Err(problem)) => {
            problems.push(format!("assembly control: {problem}"));
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

struct Assembly {
    shards: Vec<String>,
    codegen_units: u32,
    local_thin_lto: bool,
}

/// Builds a target's release library, probes the shipped binary, then emits
/// assembly from the harness with the library's effective release CGU count.
fn release_assembly(
    tools: &Tools,
    root: &Path,
    harness: &Path,
    dir: &Path,
    target: &str,
) -> Result<Assembly, Error> {
    let shipped = tools.build(root, dir, target, Stage::Library, |command| {
        command.args(["--locked", "--lib", "-p", os::CRATE]);
    })?;
    let library = shipped
        .get("ironafs_os")
        .ok_or_else(|| refusal("no workspace ironafs-os release invocation"))?;
    check_externs(&shipped)?;

    let binary = tools.build(root, dir, target, Stage::Binary, |command| {
        command.args(["--locked", "-p", "ironafs-cli", "--bin", "afs"]);
    })?;
    for caller in binary.values() {
        caller.compare(library).map_err(refusal)?;
    }
    check_externs(&binary)?;

    let harness = tools.build(root, dir, target, Stage::Assembly, |command| {
        command
            .arg("--lib")
            .arg("--manifest-path")
            .arg(harness.join("Cargo.toml"))
            .args(["--", "--emit", "asm", "-C"])
            .arg(format!("codegen-units={}", library.units()));
    })?;
    let dependency = harness
        .get("ironafs_os")
        .ok_or_else(|| refusal("no harness ironafs-os dependency invocation"))?;
    let emitter = harness
        .get(HARNESS)
        .ok_or_else(|| refusal("no harness assembly invocation"))?;
    for caller in [dependency, emitter] {
        caller.compare(library).map_err(refusal)?;
    }
    check_externs(&harness)?;
    if !matches!(emitter.externs.as_slice(), [path] if is_extern_of(path, dependency)) {
        return Err(refusal(
            "the harness did not use the captured ironafs-os dependency",
        ));
    }
    Ok(Assembly {
        shards: shards::collect(emitter)?,
        codegen_units: emitter.units(),
        local_thin_lto: emitter.local_thin_lto(),
    })
}

/// Writes the harness crate, with `source` as its library, into `dir`.
fn write_harness(dir: &Path, crate_dir: &Path, profile: &str, source: &str) -> Result<(), Error> {
    let mut manifest = String::from(
        "# Generated by `cargo xtask check-wipe`; never shipped.\n\
         [package]\nname = \"ironafs-wipe-gate\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
         publish = false\n\n[dependencies]\n",
    );
    let _ = writeln!(
        manifest,
        "ironafs-os = {{ path = {:?} }}\n\n# Its own workspace, so the repository's does not claim it.\n[workspace]\n\n# The workspace's release profile, copied.\n{profile}",
        crate_dir.display().to_string()
    );
    crate::fixture::write_file(&dir.join("Cargo.toml"), &manifest)?;
    crate::fixture::write_file(&dir.join("src").join("lib.rs"), source)
}

/// Runs the gate on every allowlisted Linux target the toolchain has, or
/// with `self_test` proves, through the same builds, that it fails on each
/// planted regression.
///
/// # Errors
///
/// Returns the targets on which it failed, or why it could not run.
pub(super) fn run(self_test: bool, output: &mut impl Write) -> Result<(), Error> {
    let workspace = metadata::load_in(None, &[], |command| {
        os::pin::without_wrappers(command);
        command.arg("--offline");
    })?;
    let crate_dir = os::crate_dir(&workspace)?;
    let tools = Tools::resolve(&workspace.root)?;
    let manifest_path = workspace.root.join("Cargo.toml");
    let manifest = fs::read_to_string(&manifest_path)
        .map_err(Error::path_io("read manifest", &manifest_path))?;
    let profile = profile_table(&manifest).ok_or(Error::UnexpectedOutput(
        "Cargo.toml: no [profile.release] table",
    ))?;
    if self_test {
        return self_test::run(&tools, &workspace, &crate_dir, &profile, output);
    }
    let dir = crate::fixture::fresh_dir(&workspace.target_dir, CHECK)?;
    let result = check_targets(
        &tools,
        &workspace.root,
        &crate_dir,
        &profile,
        HARNESS_SOURCE,
        &dir,
        output,
    );
    crate::fixture::remove_dir(&dir)?;
    result
}

/// The allowlisted Linux targets the pinned toolchain has here.
fn installed_targets(tools: &Tools) -> Vec<&'static str> {
    options::TARGETS
        .into_iter()
        .filter(|target| tools.pinned.has_target(target))
        .collect()
}

/// Runs the gate in `dir`, with a harness of `source` under `profile`.
fn check_targets(
    tools: &Tools,
    root: &Path,
    crate_dir: &Path,
    profile: &str,
    source: &str,
    dir: &Path,
    output: &mut impl Write,
) -> Result<(), Error> {
    let harness = dir.join("harness");
    write_harness(&harness, crate_dir, profile, source)?;
    let mut violations = Vec::new();
    let mut passed = 0_usize;
    let mut report =
        |line: String| writeln!(output, "{line}").map_err(Error::io("report check-wipe"));
    for target in ALLOWLIST
        .iter()
        .copied()
        .filter(|target| target.contains("-linux-"))
    {
        let Some(arch) = Arch::of(target) else {
            violations.push(format!(
                "{target}: an architecture whose zero byte store this check cannot read, so \
                 the gate cannot run there"
            ));
            continue;
        };
        if !tools.pinned.has_target(target) {
            report(format!(
                "{target}: MISSING: the toolchain has no standard library for it, so the gate \
                 has not run and mem-wipe does not ship there"
            ))?;
            continue;
        }
        let assembly = match release_assembly(tools, root, &harness, &dir.join(target), target) {
            Ok(assembly) => assembly,
            Err(Error::Rules {
                violations: failed, ..
            }) => {
                violations.extend(
                    failed
                        .into_iter()
                        .map(|problem| format!("{target}: {problem}")),
                );
                continue;
            }
            Err(error) => return Err(error),
        };
        match judge(assembly.shards.iter().map(String::as_str), arch) {
            Ok(()) => {
                passed += 1;
                let lto = if assembly.local_thin_lto { "on" } else { "off" };
                report(format!(
                    "{target}: passed: wipe inlined in both cases, at least {LENGTH} zero byte \
                     stores in each, the control's plain overwrite (the fence kept) removed, \
                     and the harness built with the workspace's release options ({} codegen \
                     units, local ThinLTO {lto}, assembly shard count {})",
                    assembly.codegen_units,
                    assembly.shards.len(),
                ))?;
            }
            Err(problems) => violations.extend(
                problems
                    .into_iter()
                    .map(|problem| format!("{target}: {problem}")),
            ),
        }
    }
    if passed == 0 && violations.is_empty() {
        violations.push("no Linux target's standard library is installed: nothing ran".to_owned());
    }
    if violations.is_empty() {
        Ok(())
    } else {
        Err(Error::Rules {
            check: CHECK,
            violations,
        })
    }
}
