//! `check-wipe`: the release-assembly gate of `ironafs-os`'s `mem-wipe`
//! site (ADR 0005, sheet 24, "Release gate").
//!
//! `wipe` has no foreign item, so the C check of point 5.6 has nothing to
//! prove; what must be shown is that its zero stores survive the shipping
//! profile. For each allowlisted Linux target whose standard library the
//! toolchain has, this check writes a small harness crate that calls the
//! production `wipe` (the crate itself, by path, not a copy), builds it
//! under the workspace's own `[profile.release]` (copied from the root
//! manifest, not restated), emits its assembly and reads four functions:
//!
//! - `wiped_live`: a buffer read after the wipe;
//! - `wiped_dead`: a buffer on the stack, wiped just before it goes out of
//!   scope, in one function, so the optimiser sees the whole lifetime and
//!   no call follows the wipe;
//! - `plain_dead`: the control of sheet 24, the same with `wipe`'s body
//!   with a plain write in place of the volatile one (the fence kept); and
//!   `untouched_dead`, the same with no overwrite at all.
//!
//! It passes on a target when both wiped cases hold no reference to
//! `ironafs-os` (so `wipe`'s body is inlined there) and at least one zero
//! byte store per byte of the buffer, and the control compiles to the same
//! instructions as `untouched_dead` (its stores are gone). If `wipe` is not
//! inlined, or the control keeps its stores, the dead-buffer case shows
//! nothing on that target and it fails. A target whose standard library is
//! not installed is reported MISSING: `mem-wipe` does not ship there.
//!
//! Workspace library, harness and binary builds are compared using the
//! pinned compiler's actual arguments. The binary probe stops before linking
//! and refuses LTO modes that require a linked harness. Fresh assembly shards
//! are read only after the emitting invocation matches the release settings.
//!
//! `--self-test` runs the same builds on the clean harness, which must
//! pass, and on planted regressions (`wipe` not inlined, too few zero
//! stores, a control whose stores survive, another profile), each of which
//! must fail on every target the gate runs on (`docs/workflow.md` §3b).

