const CHECK: &str = "check-wipe";

/// The harness crate's name, as its symbols carry it.
const HARNESS: &str = "ironafs_wipe_gate";

/// The buffer's length in every case.
const LENGTH: usize = 64;

/// The harness's source: each case a function of its own, never inlined
/// into another, so its body is found by name.
const HARNESS_SOURCE: &str = "//! Generated by `cargo xtask check-wipe`; never shipped.\n\
\n\
/// A buffer read after the wipe.\n\
#[inline(never)]\n\
pub fn wiped_live(fill: u8) -> u8 {\n\
    let mut buffer = [fill; 64];\n\
    core::hint::black_box(&mut buffer);\n\
    ironafs_os::wipe(&mut buffer);\n\
    buffer.iter().fold(0, |all, byte| all | byte)\n\
}\n\
\n\
/// A buffer on the stack, wiped just before it goes out of scope.\n\
#[inline(never)]\n\
pub fn wiped_dead(fill: u8) {\n\
    let mut buffer = [fill; 64];\n\
    ironafs_os::wipe(&mut buffer);\n\
}\n\
\n\
/// The control: `wipe`'s body with a plain write in place of the\n\
/// volatile one, the fence kept.\n\
#[inline(never)]\n\
pub fn plain_dead(fill: u8) {\n\
    let mut buffer = [fill; 64];\n\
    for byte in buffer.iter_mut() {\n\
        *byte = 0;\n\
    }\n\
    core::sync::atomic::compiler_fence(core::sync::atomic::Ordering::SeqCst);\n\
}\n\
\n\
/// The same buffer with no overwrite at all.\n\
#[inline(never)]\n\
pub fn untouched_dead(fill: u8) {\n\
    let buffer = [fill; 64];\n\
    core::mem::drop(buffer);\n\
}\n";

/// The architectures of the Linux targets, by their zero byte store.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Arch {
    /// `movb $0, <memory>`.
    X86_64,
    /// `strb wzr, <memory>`.
    Aarch64,
}

impl Arch {
    fn of(target: &str) -> Option<Self> {
        if target.starts_with("x86_64-") {
            Some(Self::X86_64)
        } else if target.starts_with("aarch64-") {
            Some(Self::Aarch64)
        } else {
            None
        }
    }
}

/// The `[profile.release]` table of a manifest, up to the next table;
/// `None` if there is none, or if any `[profile.release.*]` table (a
/// per-package or build-override setting) changes the profile beside it.
pub(crate) fn profile_table(manifest: &str) -> Option<String> {
    if manifest
        .lines()
        .any(|line| line.trim_start().starts_with("[profile.release."))
    {
        return None;
    }
    let mut lines = manifest.lines();
    lines
        .by_ref()
        .find(|line| line.trim() == "[profile.release]")?;
    let mut table: Vec<&str> = lines
        .take_while(|line| !line.trim_start().starts_with('['))
        .collect();
    while table.last().is_some_and(|line| line.trim().is_empty()) {
        table.pop();
    }
    let mut text = "[profile.release]\n".to_owned();
    for line in table {
        text.push_str(line);
        text.push('\n');
    }
    Some(text)
}

/// The symbol a label line defines.
fn label(line: &str) -> Option<&str> {
    if line.starts_with(char::is_whitespace) {
        return None;
    }
    line.strip_suffix(':')
}

/// Whether `symbol` names the function `name`: a symbol of the harness
/// crate holding `name` with its length before it, as both Rust manglings
/// write it, and no further name character after it.
fn names(symbol: &str, name: &str) -> bool {
    if !symbol.contains(HARNESS) {
        return false;
    }
    let segment = format!("{}{name}", name.len());
    symbol.match_indices(segment.as_str()).any(|(at, _)| {
        !symbol
            .get(at + segment.len()..)
            .and_then(|after| after.chars().next())
            .is_some_and(|next| next.is_ascii_alphabetic() || next == '_')
    })
}

/// The lines of the function whose symbol carries `name` (length-prefixed,
/// as both Rust manglings write it), from after its label to its end. A
/// function the compiler emitted as an alias of another (`a = b`, when
/// both compile to the same code) has the other's lines.
pub(crate) fn body<'a>(asm: &'a str, name: &str) -> Option<Vec<&'a str>> {
    let mut lines = asm.lines();
    if lines
        .by_ref()
        .find(|line| label(line).is_some_and(|symbol| names(symbol, name)))
        .is_none()
    {
        let target = asm.lines().find_map(|line| {
            let (alias, target) = line.split_once(" = ")?;
            (!alias.starts_with(char::is_whitespace) && names(alias, name)).then_some(target.trim())
        })?;
        lines = asm.lines();
        lines.by_ref().find(|line| label(line) == Some(target))?;
    }
    Some(
        lines
            .take_while(|line| {
                let ends_function = line.starts_with(".Lfunc_end")
                    || line.trim_start().starts_with(".size")
                    || (!line.starts_with(char::is_whitespace)
                        && !line.starts_with(".L")
                        && line.ends_with(':'));
                !ends_function
            })
            .collect(),
    )
}

/// How many lines of `lines` store a zero byte to memory.
pub(crate) fn zero_byte_stores(lines: &[&str], arch: Arch) -> usize {
    let (mnemonic, source) = match arch {
        Arch::X86_64 => ("movb", "$0,"),
        Arch::Aarch64 => ("strb", "wzr,"),
    };
    lines
        .iter()
        .filter(|line| {
            let mut words = line.split_whitespace();
            words.next() == Some(mnemonic) && words.next() == Some(source)
        })
        .count()
}

/// `text` with the numbers after each local label prefix (`.LBB`,
/// `.Ltmp`) dropped, so two functions' labels compare equal.
fn without_label_numbers(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some((head, tail)) = [".LBB", ".Ltmp"]
        .iter()
        .filter_map(|prefix| rest.find(prefix).map(|at| at + prefix.len()))
        .min()
        .and_then(|end| rest.split_at_checked(end))
    {
        out.push_str(head);
        rest = tail.trim_start_matches(|c: char| c.is_ascii_digit() || c == '_');
    }
    out.push_str(rest);
    out
}

/// The instructions of `lines`, without directives, labels or comments,
/// with whitespace collapsed and local label numbers dropped.
pub(crate) fn normalized(lines: &[&str]) -> Vec<String> {
    lines
        .iter()
        .map(|line| line.trim())
        .filter(|line| {
            !line.is_empty()
                && !line.starts_with('.')
                && !line.starts_with('#')
                && !line.starts_with("//")
                && !line.ends_with(':')
        })
        .map(|line| without_label_numbers(&line.split_whitespace().collect::<Vec<_>>().join(" ")))
        .collect()
}

/// Judges one target's assembly; returns every problem found.
pub(crate) fn judge(asm: &str, arch: Arch) -> Result<(), Vec<String>> {
    let mut problems = Vec::new();
    for case in ["wiped_live", "wiped_dead"] {
        let Some(lines) = body(asm, case) else {
            problems.push(format!("no function `{case}` in the assembly"));
            continue;
        };
        // `10ironafs_os` is the crate's name as both manglings write it.
        if lines.iter().any(|line| line.contains("10ironafs_os")) {
            problems.push(format!(
                "`{case}` refers to ironafs-os, so `wipe` is not inlined there and the case \
                 shows nothing"
            ));
        }
        let stores = zero_byte_stores(&lines, arch);
        if stores < LENGTH {
            problems.push(format!(
                "`{case}` has {stores} zero byte stores for a buffer of {LENGTH} bytes"
            ));
        }
    }
    match (body(asm, "plain_dead"), body(asm, "untouched_dead")) {
        (Some(plain), Some(untouched)) => {
            if normalized(&plain) != normalized(&untouched) {
                problems.push(
                    "the control `plain_dead` (a plain overwrite, the fence kept) compiles to \
                     more than `untouched_dead`: its stores survive, so the dead-buffer case \
                     shows nothing on this target"
                        .to_owned(),
                );
            }
        }
        _ => problems.push("no control functions in the assembly".to_owned()),
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(problems)
    }
}

/// Builds the harness for `target` and returns its assembly, or why it
/// could not be built.
fn assembly(
    workspace: &Workspace,
    harness: &Path,
    build_dir: &Path,
    target: &str,
) -> Result<Result<String, String>, Error> {
    let mut command = Command::new("cargo");
    command
        .current_dir(&workspace.root)
        .args(["rustc", "--release", "--lib", "--offline", "--quiet"])
        .arg("--manifest-path")
        .arg(harness.join("Cargo.toml"))
        .args(["--target", target])
        .arg("--target-dir")
        .arg(build_dir)
        .args(["--", "--emit", "asm"]);
    for name in CLEARED_ENVIRONMENT {
        command.env_remove(name);
    }
    let output = command.output().map_err(Error::io("cargo rustc"))?;
    if !output.status.success() {
        return Ok(Err(format!(
            "the harness did not build: {}",
            first_error(&output.stderr)
        )));
    }
    let mut found = Vec::new();
    find_assembly(&build_dir.join(target), &mut found)?;
    match found.as_slice() {
        [file] => fs::read_to_string(file)
            .map(Ok)
            .map_err(Error::path_io("read assembly", file)),
        _ => Ok(Err(format!(
            "expected one assembly file of the harness, found {}",
            found.len()
        ))),
    }
}

/// Every `.s` file of the harness under `dir`.
fn find_assembly(dir: &Path, found: &mut Vec<PathBuf>) -> Result<(), Error> {
    let entries = fs::read_dir(dir).map_err(Error::path_io("list build directory", dir))?;
    for entry in entries {
        let path = entry
            .map_err(Error::path_io("list build directory", dir))?
            .path();
        if path.is_dir() {
            find_assembly(&path, found)?;
        } else if path.extension().is_some_and(|extension| extension == "s")
            && path
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.starts_with(HARNESS))
        {
            found.push(path);
        }
    }
    Ok(())
}

/// The toolchain's sysroot, from `rustc --print sysroot` run in the
/// workspace, so the workspace's pinned toolchain answers.
fn sysroot(workspace: &Workspace) -> Result<PathBuf, Error> {
    let output = Command::new("rustc")
        .current_dir(&workspace.root)
        .args(["--print", "sysroot"])
        .output()
        .map_err(Error::io("run rustc --print sysroot"))?;
    Error::check_status("rustc --print sysroot", output.status)?;
    let text = String::from_utf8_lossy(&output.stdout);
    Ok(PathBuf::from(text.trim()))
}

/// Writes the harness crate into `dir`.
fn write_harness(dir: &Path, crate_dir: &Path, profile: &str) -> Result<(), Error> {
    let mut manifest = String::from(
        "# Generated by `cargo xtask check-wipe`; never shipped.\n\
         [package]\nname = \"ironafs-wipe-gate\"\nversion = \"0.0.0\"\nedition = \"2024\"\n\
         publish = false\n\n[dependencies]\n",
    );
    let _ = writeln!(
        manifest,
        "ironafs-os = {{ path = {:?} }}\n\n# Its own workspace, so the repository's does not claim it.\n[workspace]\n\n# The workspace's release profile, copied.\n{profile}",
        crate_dir.display().to_string()
    );
    crate::fixture::write_file(&dir.join("Cargo.toml"), &manifest)?;
    crate::fixture::write_file(&dir.join("src").join("lib.rs"), HARNESS_SOURCE)
}

/// Runs the gate on every allowlisted Linux target the toolchain has.
///
/// # Errors
///
/// Returns the targets on which it failed, or why it could not run.
pub(super) fn run(output: &mut impl Write) -> Result<(), Error> {
    let workspace = metadata::load(None, &[])?;
    let crate_dir = os::crate_dir(&workspace)?;
    let manifest_path = workspace.root.join("Cargo.toml");
    let manifest = fs::read_to_string(&manifest_path)
        .map_err(Error::path_io("read manifest", &manifest_path))?;
    let profile = profile_table(&manifest).ok_or(Error::UnexpectedOutput(
        "Cargo.toml: no [profile.release] table, or a [profile.release.*] table beside it, \
         which the harness would not copy",
    ))?;
    let dir = crate::fixture::fresh_dir(&workspace.target_dir, CHECK)?;
    let result = check_targets(&workspace, &crate_dir, &profile, &dir, output);
    crate::fixture::remove_dir(&dir)?;
    result
}

fn check_targets(
    workspace: &Workspace,
    crate_dir: &Path,
    profile: &str,
    dir: &Path,
    output: &mut impl Write,
) -> Result<(), Error> {
    let harness = dir.join("harness");
    write_harness(&harness, crate_dir, profile)?;
    let sysroot = sysroot(workspace)?;
    let mut violations = Vec::new();
    let mut passed = 0_usize;
    let mut report =
        |line: String| writeln!(output, "{line}").map_err(Error::io("report check-wipe"));
    for target in ALLOWLIST.iter().filter(|target| target.contains("-linux-")) {
        let Some(arch) = Arch::of(target) else {
            violations.push(format!(
                "{target}: an architecture whose zero byte store this check cannot read, so \
                 the gate cannot run there"
            ));
            continue;
        };
        if !sysroot
            .join("lib")
            .join("rustlib")
            .join(target)
            .join("lib")
            .is_dir()
        {
            report(format!(
                "{target}: MISSING: the toolchain has no standard library for it, so the gate \
                 has not run and mem-wipe does not ship there"
            ))?;
            continue;
        }
        let asm = match assembly(workspace, &harness, &dir.join("target"), target)? {
            Ok(asm) => asm,
            Err(error) => {
                violations.push(format!("{target}: {error}"));
                continue;
            }
        };
        match judge(&asm, arch) {
            Ok(()) => {
                passed += 1;
                report(format!(
                    "{target}: passed: wipe inlined in both cases, at least {LENGTH} zero byte \
                     stores in each, and the control's plain overwrite (the fence kept) removed"
                ))?;
            }
            Err(problems) => violations.extend(
                problems
                    .into_iter()
                    .map(|problem| format!("{target}: {problem}")),
            ),
        }
    }
    if passed == 0 && violations.is_empty() {
        violations.push("no Linux target's standard library is installed: nothing ran".to_owned());
    }
    if violations.is_empty() {
        Ok(())
    } else {
        Err(Error::Rules {
            check: CHECK,
            violations,
        })
    }
}
